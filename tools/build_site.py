def build_doc_pages(out: str) -> None:
    for md, page, title, description in PAGES:
        with open(os.path.join(DOCS, md), encoding="utf-8") as fh:
            source = fh.read()
        body, toc = render_markdown(source)
        # The first h1 becomes the page header, so it is not repeated in the
        # article and not listed in its own contents.
        body = re.sub(r"^<h1 .*?</h1>\n?", "", body, count=1)
        toc = [t for t in toc if t[0] > 1]
        items = "".join(
            f'<a class="lvl{lvl}" href="#{ident}">{html.escape(text)}</a>'
            for lvl, ident, text in toc)
        article = f"""<div class="doc">
  <aside class="toc" aria-label="On this page">
    <div class="toc-inner">
      <p class="toc-title">On this page</p>
      <nav>{items}</nav>
      <p class="toc-source"><a href="{BLOB}/{DOCS}/{md}">View source on GitHub</a></p>
    </div>
  </aside>
  <article class="prose">
    <p class="eyebrow">{html.escape(description)}</p>
    <h1>{html.escape(title)}</h1>
    {body}
  </article>
</div>"""
        with open(os.path.join(out, page), "w", encoding="utf-8") as fh:
            fh.write(shell(f"{title} — rust_physics_engine", description,
                           article, page.replace(".html", "")))


def main() -> int:
    if not os.path.isdir(SITE):
        print("run from the repository root", file=sys.stderr)
        return 2
    out = OUT
    if "--out" in sys.argv:
        out = sys.argv[sys.argv.index("--out") + 1]

    if os.path.isdir(out):
        shutil.rmtree(out)
    shutil.copytree(SITE, out)
    os.makedirs(os.path.join(out, "assets"), exist_ok=True)
    shutil.copy("assets/banner.svg", os.path.join(out, "assets", "banner.svg"))
    open(os.path.join(out, ".nojekyll"), "w").close()

    totals = write_module_data(out)
    build_doc_pages(out)
    print(f"built {out}: {totals['modules']} modules, "
          f"{totals['fns']:,} public functions and methods")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
