#!/usr/bin/env python3
"""Assemble the static site published to GitHub Pages.

Nothing this produces is committed. The workflow in
`.github/workflows/pages.yml` runs it into a scratch directory and then
drops the rustdoc output alongside, so no generated page can be stale --
the same reason `docs/MODULE_MAP.md` is checked rather than hand-written.

Three things happen here:

* **Module data.** `modules.js` is derived from the source tree by the
  scanner `tools/gen_module_map.py` already uses, so the counts on the
  front page and the counts in the module map come from one place and
  cannot disagree.
* **Prose pages.** `docs/GUIDE.md` and `docs/MODULE_MAP.md` become
  `guide.html` and `module-map.html` in the site's own styling, with a
  table of contents built from their headings.
* **Static files.** Everything under `site/`, plus the banner.

    python3 tools/build_site.py             # build into _site/
    python3 tools/build_site.py --out DIR   # build somewhere else
"""

from __future__ import annotations

import html
import json
import os
import re
import shutil
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from gen_module_map import AREAS, collect, public_top_levels  # noqa: E402

SITE = "site"
DOCS = "docs"
OUT = "_site"
REPO = "https://github.com/Magic-Man-us/RustPhysicsEngine"
BLOB = f"{REPO}/blob/main"

# Which markdown files become pages, and what the page is called.
PAGES = [
    ("GUIDE.md", "guide.html", "Guide",
     "A walk through the library by doing things with it."),
    ("MODULE_MAP.md", "module-map.html", "Module map",
     "Every module in the crate, with its size and summary."),
]


# --------------------------------------------------------------------------
# Module data
# --------------------------------------------------------------------------

def module_rows() -> tuple[list[dict], dict]:
    """One row per public top-level module, plus the crate totals.

    A module's figures are the sum over every file beneath it -- `cfd` is
    16,732 lines across its submodules, not the 500 in `cfd/mod.rs` -- and
    its summary is the first sentence of its own `//!` block. Counts come
    from the scanner behind `docs/MODULE_MAP.md`, so the two agree by
    construction rather than by transcription.
    """
    mods = collect()
    public = public_top_levels()
    area_of = {name: area for area, names in AREAS for name in names}

    rows = []
    for top in sorted({m.split("::")[0] for m in mods if m != "lib"} & public):
        files = [m for name, m in mods.items()
                 if name == top or name.startswith(f"{top}::")]
        summary = mods.get(top, {}).get("summary", "—").replace(r"\|", "|")
        rows.append({
            "name": top,
            "area": area_of.get(top, "Other"),
            "lines": sum(f["lines"] for f in files),
            "fns": sum(f["free"] + f["meth"] for f in files),
            "types": sum(f["types"] for f in files),
            "files": len(files),
            "summary": summary,
        })

    totals = {
        "modules": len(rows),
        # Every source file, not only those under a public module, so this
        # agrees with the count the README and the module map quote.
        "files": len(mods),
        "lines": sum(m["lines"] for m in mods.values()),
        "fns": sum(m["free"] + m["meth"] for m in mods.values()),
        "free": sum(m["free"] for m in mods.values()),
        "methods": sum(m["meth"] for m in mods.values()),
        "types": sum(m["types"] for m in mods.values()),
    }
    return rows, totals


def write_module_data(out: str) -> None:
    rows, totals = module_rows()
    areas = [a for a, _ in AREAS] + ["Other"]
    areas = [a for a in areas if any(r["area"] == a for r in rows)]
    body = (
        "// Generated by tools/build_site.py from the source tree. Do not edit.\n"
        f"window.MODULES = {json.dumps(rows, ensure_ascii=False)};\n"
        f"window.MODULE_AREAS = {json.dumps(areas, ensure_ascii=False)};\n"
        f"window.CRATE_TOTALS = {json.dumps(totals)};\n"
    )
    with open(os.path.join(out, "modules.js"), "w", encoding="utf-8") as fh:
        fh.write(body)
    return totals


# --------------------------------------------------------------------------
# Markdown
# --------------------------------------------------------------------------
#
# A converter for exactly the markdown these two files use -- headings,
# fenced code, GFM tables, lists, rules, and the four inline forms. It is
# forty lines rather than a dependency because the crate has none, and
# because the input is two files in this repository rather than arbitrary
# text from anywhere.

INLINE = re.compile(
    r"`([^`]+)`"                       # code
    r"|\*\*([^*]+)\*\*"                # bold
    r"|(?<!\*)\*([^*\n]+)\*(?!\*)"     # italic
    r"|\[([^\]]+)\]\(([^)]+)\)"        # link
)


def rewrite_href(href: str) -> str:
    """Point a repository-relative link at the right place.

    Links between the two markdown files stay inside the site; anything
    else that names a path in the repository goes to GitHub, because the
    site does not publish the source tree.
    """
    if href.startswith(("http://", "https://", "#", "mailto:")):
        return href
    target = href.split("#", 1)
    path, frag = target[0], ("#" + target[1] if len(target) > 1 else "")
    base = os.path.normpath(os.path.join(DOCS, path)) if not path.startswith(("/", "docs/")) \
        else os.path.normpath(path.lstrip("/"))
    for md, page, _t, _d in PAGES:
        if base == os.path.join(DOCS, md):
            return page + frag
    return f"{BLOB}/{base}{frag}"


def inline(text: str) -> str:
    out, pos = [], 0
    for m in INLINE.finditer(text):
        out.append(html.escape(text[pos:m.start()]))
        code, bold, ital, label, href = m.groups()
        if code is not None:
            out.append(f"<code>{html.escape(code)}</code>")
        elif bold is not None:
            out.append(f"<strong>{inline(bold)}</strong>")
        elif ital is not None:
            out.append(f"<em>{inline(ital)}</em>")
        else:
            out.append(f'<a href="{html.escape(rewrite_href(href), quote=True)}">'
                       f"{inline(label)}</a>")
        pos = m.end()
    out.append(html.escape(text[pos:]))
    return "".join(out)


def slug(text: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", re.sub(r"`|\*|\\", "", text).lower())
    return s.strip("-") or "section"


def render_markdown(md: str) -> tuple[str, list[tuple[int, str, str]]]:
    """Return the HTML body and the (level, id, text) of every heading."""
    lines = md.split("\n")
    out: list[str] = []
    toc: list[tuple[int, str, str]] = []
    seen: dict[str, int] = {}
    i = 0

    def close_para(buf: list[str]) -> None:
        if buf:
            out.append(f"<p>{inline(' '.join(buf))}</p>")
            buf.clear()

    para: list[str] = []
    while i < len(lines):
        line = lines[i]

        if line.startswith("```"):
            close_para(para)
            lang = line[3:].strip()
            i += 1
            block = []
            while i < len(lines) and not lines[i].startswith("```"):
                block.append(lines[i])
                i += 1
            i += 1
            cls = f' class="lang-{html.escape(lang, quote=True)}"' if lang else ""
            out.append(f'<div class="code"><button class="copy" type="button"'
                       f' aria-label="Copy code">Copy</button>'
                       f"<pre><code{cls}>{html.escape(chr(10).join(block))}</code></pre></div>")
            continue

        if re.match(r"^#{1,6} ", line):
            close_para(para)
            level = len(line) - len(line.lstrip("#"))
            text = line[level:].strip()
            base = slug(text)
            seen[base] = seen.get(base, 0) + 1
            ident = base if seen[base] == 1 else f"{base}-{seen[base]}"
            if level <= 3:
                toc.append((level, ident, re.sub(r"`", "", text)))
            out.append(f'<h{level} id="{ident}">{inline(text)}'
                       f'<a class="anchor" href="#{ident}" aria-label="Link to this section">#</a>'
                       f"</h{level}>")
            i += 1
            continue

        if re.match(r"^(-{3,}|\*{3,}|_{3,})\s*$", line):
            close_para(para)
            out.append("<hr>")
            i += 1
            continue

        if line.startswith("|") and i + 1 < len(lines) and re.match(
                r"^\|[\s:\-|]+\|?\s*$", lines[i + 1]):
            close_para(para)
            def cells(row: str) -> list[str]:
                return [c.strip() for c in row.strip().strip("|").split("|")]
            head = cells(line)
            align = []
            for spec in cells(lines[i + 1]):
                if spec.startswith(":") and spec.endswith(":"):
                    align.append(" style=\"text-align:center\"")
                elif spec.endswith(":"):
                    align.append(" style=\"text-align:right\"")
                else:
                    align.append("")
            i += 2
            body = []
            while i < len(lines) and lines[i].startswith("|"):
                body.append(cells(lines[i]))
                i += 1
            out.append('<div class="table-wrap"><table><thead><tr>' + "".join(
                f"<th{align[n] if n < len(align) else ''}>{inline(c)}</th>"
                for n, c in enumerate(head)) + "</tr></thead><tbody>")
            for row in body:
                out.append("<tr>" + "".join(
                    f"<td{align[n] if n < len(align) else ''}>{inline(c)}</td>"
                    for n, c in enumerate(row)) + "</tr>")
            out.append("</tbody></table></div>")
            continue

        bullet = re.match(r"^(\s*)([-*]|\d+\.)\s+(.*)$", line)
        if bullet:
            close_para(para)
            ordered = not bullet.group(2) in ("-", "*")
            tag = "ol" if ordered else "ul"
            items: list[list[str]] = []
            while i < len(lines):
                m = re.match(r"^(\s*)([-*]|\d+\.)\s+(.*)$", lines[i])
                if m and (m.group(2) not in ("-", "*")) == ordered:
                    items.append([m.group(3)])
                    i += 1
                    # A continuation line is indented and is not itself an item.
                    while (i < len(lines) and lines[i].strip()
                           and not re.match(r"^(\s*)([-*]|\d+\.)\s+", lines[i])
                           and lines[i].startswith((" ", "\t"))):
                        items[-1].append(lines[i].strip())
                        i += 1
                elif not lines[i].strip() and i + 1 < len(lines) and re.match(
                        r"^(\s*)([-*]|\d+\.)\s+", lines[i + 1]):
                    i += 1
                else:
                    break
            out.append(f"<{tag}>" + "".join(
                f"<li>{inline(' '.join(it))}</li>" for it in items) + f"</{tag}>")
            continue

        if line.startswith(">"):
            close_para(para)
            quote = []
            while i < len(lines) and lines[i].startswith(">"):
                quote.append(lines[i].lstrip(">").strip())
                i += 1
            out.append(f"<blockquote><p>{inline(' '.join(quote))}</p></blockquote>")
            continue

        if not line.strip():
            close_para(para)
            i += 1
            continue

        para.append(line.strip())
        i += 1

    close_para(para)
    return "\n".join(out), toc


