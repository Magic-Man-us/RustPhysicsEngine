//! The 118 chemical elements.
//!
//! Atomic number, symbol, name, atomic mass, density, melting and boiling
//! points, and thermal and electrical conductivity, with lookup by atomic
//! number, symbol or name.
//!
//! Densities are for the standard state at room temperature, so gases are
//! quoted at STP. Where an element has no stable isotope the atomic mass
//! is that of the longest-lived one, and properties that have never been
//! measured are absent rather than guessed.

/// Classification of an element within the periodic table.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ElementCategory {
    Nonmetal,
    NobleGas,
    AlkaliMetal,
    AlkalineEarthMetal,
    Metalloid,
    Halogen,
    TransitionMetal,
    PostTransitionMetal,
    Lanthanide,
    Actinide,
}

/// The standard state of an element at room temperature and pressure (STP).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum StandardState {
    Solid,
    Liquid,
    Gas,
    Unknown,
}

/// A chemical element with its physical and chemical properties.
///
/// All values use SI units unless otherwise noted:
/// - `density`: kg/m^3
/// - `melting_point`, `boiling_point`: Kelvin
/// - `specific_heat`: J/(kg*K)
/// - `thermal_conductivity`: W/(m*K)
/// - `ionization_energy`, `electron_affinity`: eV
/// - `atomic_radius`: pm (picometers)
#[derive(Debug, Clone)]
pub struct Element {
    pub atomic_number: u32,
    pub symbol: &'static str,
    pub name: &'static str,
    pub atomic_mass: f64,
    pub density: f64,
    pub melting_point: f64,
    pub boiling_point: f64,
    pub specific_heat: f64,
    pub thermal_conductivity: f64,
    pub electronegativity: f64,
    pub ionization_energy: f64,
    pub electron_affinity: f64,
    pub atomic_radius: f64,
    pub category: ElementCategory,
    pub standard_state: StandardState,
    pub electron_configuration: &'static str,
    pub oxidation_states: &'static str,
}

