/// Looks up an element by its atomic number (1..=118).
///
/// Returns `None` if `z` is outside the valid range.
/// This is an O(1) direct index lookup.
pub fn by_atomic_number(z: u32) -> Option<&'static Element> {
    if (1..=118).contains(&z) {
        Some(&ELEMENTS[(z - 1) as usize])
    } else {
        None
    }
}

/// Looks up an element by its chemical symbol (case-sensitive, e.g. "He", "Fe").
///
/// Performs a linear scan over the 118 elements with direct string comparison.
pub fn by_symbol(symbol: &str) -> Option<&'static Element> {
    ELEMENTS.iter().find(|e| e.symbol == symbol)
}

/// O(1) lookup for commonly used element symbols, falling back to linear scan.
///
/// Covers the 27 most frequently looked-up elements (H, He, Li, Be, B, C, N,
/// O, F, Ne, Na, Mg, Al, Si, P, S, Cl, Ar, K, Ca, Fe, Cu, Zn, Ag, Au, Pb, U)
/// via a match statement that returns a direct index into the static array.
/// All other symbols fall back to [`by_symbol`].
pub fn by_symbol_static(symbol: &str) -> Option<&'static Element> {
    let index: Option<usize> = match symbol {
        "H" => Some(0),
        "He" => Some(1),
        "Li" => Some(2),
        "Be" => Some(3),
        "B" => Some(4),
        "C" => Some(5),
        "N" => Some(6),
        "O" => Some(7),
        "F" => Some(8),
        "Ne" => Some(9),
        "Na" => Some(10),
        "Mg" => Some(11),
        "Al" => Some(12),
        "Si" => Some(13),
        "P" => Some(14),
        "S" => Some(15),
        "Cl" => Some(16),
        "Ar" => Some(17),
        "K" => Some(18),
        "Ca" => Some(19),
        "Fe" => Some(25),
        "Cu" => Some(28),
        "Zn" => Some(29),
        "Ag" => Some(46),
        "Au" => Some(78),
        "Pb" => Some(81),
        "U" => Some(91),
        _ => None,
    };
    match index {
        Some(i) => Some(&ELEMENTS[i]),
        None => by_symbol(symbol),
    }
}

/// Looks up an element by name using case-insensitive ASCII comparison.
///
/// Zero-allocation: uses `eq_ignore_ascii_case` instead of `to_lowercase`.
pub fn by_name(name: &str) -> Option<&'static Element> {
    ELEMENTS.iter().find(|e| e.name.eq_ignore_ascii_case(name))
}

/// Returns a slice of all 118 elements, ordered by atomic number.
pub fn all() -> &'static [Element] {
    &ELEMENTS
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn all_118_elements_present() {
        assert_eq!(all().len(), 118);
    }

    #[test]
    fn hydrogen_is_element_1() {
        let h = by_atomic_number(1).unwrap();
        assert_eq!(h.symbol, "H");
        assert_eq!(h.name, "Hydrogen");
        assert!((h.atomic_mass - 1.008).abs() < 0.001);
    }

    #[test]
    fn oganesson_is_element_118() {
        let og = by_atomic_number(118).unwrap();
        assert_eq!(og.symbol, "Og");
        assert_eq!(og.name, "Oganesson");
    }

    #[test]
    fn copper_lookup_by_symbol_number_and_name() {
        let cu_sym = by_symbol("Cu").expect("Cu should exist");
        let cu_num = by_atomic_number(29).expect("Z=29 should exist");
        let cu_name = by_name("Copper").expect("Copper should exist");

        assert_eq!(cu_sym.atomic_number, 29);
        assert_eq!(cu_num.symbol, "Cu");
        assert_eq!(cu_name.symbol, "Cu");
        assert_eq!(cu_sym.symbol, cu_num.symbol);
        assert_eq!(cu_sym.symbol, cu_name.symbol);
    }

    #[test]
    fn gold_density() {
        let au = by_symbol("Au").unwrap();
        assert!((au.density - 19282.0).abs() < 1.0);
    }

    #[test]
    fn iron_melting_point() {
        let fe = by_symbol("Fe").unwrap();
        assert!((fe.melting_point - 1811.0).abs() < 1.0);
    }

    #[test]
    fn noble_gases_no_electronegativity() {
        let noble_symbols = ["He", "Ne", "Ar", "Xe", "Rn", "Og"];
        for sym in &noble_symbols {
            let elem = by_symbol(sym).unwrap();
            assert!(
                elem.electronegativity == 0.0,
                "{} should have electronegativity 0.0, got {}",
                sym,
                elem.electronegativity,
            );
            assert_eq!(elem.category, ElementCategory::NobleGas);
        }
    }

    #[test]
    fn carbon_atomic_mass() {
        let c = by_symbol("C").unwrap();
        assert!((c.atomic_mass - 12.011).abs() < 0.001);
    }

    #[test]
    fn all_elements_have_correct_index() {
        for (i, elem) in ELEMENTS.iter().enumerate() {
            assert_eq!(elem.atomic_number, (i + 1) as u32);
        }
    }

    #[test]
    fn by_name_is_case_insensitive() {
        assert!(by_name("copper").is_some());
        assert!(by_name("COPPER").is_some());
        assert!(by_name("Copper").is_some());
    }

    #[test]
    fn out_of_range_returns_none() {
        assert!(by_atomic_number(0).is_none());
        assert!(by_atomic_number(119).is_none());
        assert!(by_symbol("Unobtanium").is_none());
        assert!(by_name("Unobtanium").is_none());
    }

    #[test]
    fn bromine_is_liquid() {
        let br = by_symbol("Br").unwrap();
        assert_eq!(br.standard_state, StandardState::Liquid);
    }

    #[test]
    fn mercury_is_liquid() {
        let hg = by_symbol("Hg").unwrap();
        assert_eq!(hg.standard_state, StandardState::Liquid);
    }

    #[test]
    fn by_symbol_static_matches_by_symbol() {
        let common_symbols = [
            "H", "He", "Li", "Be", "B", "C", "N", "O", "F", "Ne",
            "Na", "Mg", "Al", "Si", "P", "S", "Cl", "Ar", "K", "Ca",
            "Fe", "Cu", "Zn", "Ag", "Au", "Pb", "U",
        ];
        for sym in &common_symbols {
            let fast = by_symbol_static(sym).expect("symbol missing from static");
            let slow = by_symbol(sym).unwrap();
            assert_eq!(fast.atomic_number, slow.atomic_number,
                "Mismatch for {sym}: static Z={}, scan Z={}", fast.atomic_number, slow.atomic_number);
        }
    }

    #[test]
    fn by_symbol_static_fallback_works() {
        let ti = by_symbol_static("Ti").expect("Ti should fall back to linear scan");
        assert_eq!(ti.name, "Titanium");
    }

    #[test]
    fn by_symbol_static_nonexistent_returns_none() {
        assert!(by_symbol_static("Xx").is_none());
    }
}
